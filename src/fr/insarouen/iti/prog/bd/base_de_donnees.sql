CREATE TABLE MONDE (
    NOM VARCHAR(30) PRIMARY KEY
);

CREATE TABLE PIECE (
    NOM VARCHAR(30) PRIMARY KEY,
    NOM_MONDE VARCHAR(30),
    FOREIGN KEY (NOM_MONDE) REFERENCES MONDE(NOM)
);

CREATE TABLE JOUEURHUMAIN(
    NOM VARCHAR(30) PRIMARY KEY,
    PT_DE_VIE INTEGER ,
    PT_DE_FORCE INTEGER,
    NOM_MONDE VARCHAR(30),
    NOM_PIECE VARCHAR(30),
    FOREIGN KEY (NOM_PIECE) REFERENCES PIECE(NOM) ,
    FOREIGN KEY (NOM_MONDE) REFERENCES MONDE(NOM) 
);

CREATE TABLE PIEDDEBICHE (
    NOM VARCHAR(30) PRIMARY KEY,
    EST_DEPLACABLE BOOLEAN,
    NOM_MONDE VARCHAR(30),
    FOREIGN KEY (NOM_MONDE) REFERENCES MONDE(NOM) 
);

CREATE TABLE PORTE(
    NOM VARCHAR(30) PRIMARY KEY ,
    NOM_MONDE VARCHAR(30),
    ETAT Varchar(100), CHECK (ETAT IN ('FERME', 'OUVERT', 'VERROUILLE','DEVERROUILLE')),
    FOREIGN KEY (NOM_MONDE) REFERENCES MONDE(NOM) 
);

CREATE TABLE POSSEDE_PIECE_PORTE (
    NOM_PIECEA VARCHAR(30),
    NOM_PIECEB VARCHAR(30),
    NOM_PORTE VARCHAR(30),
    PRIMARY KEY (NOM_PIECEA,NOM_PIECEB, NOM_PORTE),
    FOREIGN KEY (NOM_PIECEA) REFERENCES PIECE(NOM),
    FOREIGN KEY (NOM_PIECEB) REFERENCES PIECE(NOM),
    FOREIGN KEY (NOM_PORTE) REFERENCES PORTE(NOM)
);

CREATE TABLE CONTIENT_PIECE_PDB (
    NOM_PIECE VARCHAR(30),
    NOM_PDB VARCHAR(30),
    PRIMARY KEY (NOM_PIECE, NOM_PDB),
    FOREIGN KEY (NOM_PIECE) REFERENCES PIECE(NOM),
    FOREIGN KEY (NOM_PDB) REFERENCES PIEDDEBICHE(NOM)
);

CREATE TABLE POSSEDE_PDB_JH (
    NOM_PDB VARCHAR(30),
    NOM_JH VARCHAR(30),
    PRIMARY KEY (NOM_PDB, NOM_JH),
    FOREIGN KEY (NOM_PDB) REFERENCES PIEDDEBICHE(NOM),
    FOREIGN KEY (NOM_JH) REFERENCES JOUEURHUMAIN(NOM)
);
